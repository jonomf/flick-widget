#!/usr/bin/env python3
"""Generates every widget layout from shared pieces, so all sizes stay consistent.

Run from the repo root: python3 tools/gen_layouts.py
IDs: hub, update, c0..c7 (+ c0i icon, c0t label), r0..r3 (+ r0i icon, r0t title, r0s route).
Ring layouts place cell i at compass slot i (0 = N, clockwise) around the hub.
"""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "layout")
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'

# Compass slot for each position of a 3x3 grid (None = hub).
RING_GRID = [[7, 0, 1], [6, None, 2], [5, 4, 3]]


def root(inner, bg=True):
    # bg and content are separate views so the renderer can blank the widget while the ring is
    # open over it (no doubled icons).
    bg_view = ('''    <ImageView android:id="@+id/bg" android:layout_width="match_parent" android:layout_height="match_parent"
        android:src="@drawable/widget_bg" android:scaleType="fitXY" android:importantForAccessibility="no" />
''' if bg else "")
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_layouts.py; edit that, not this. -->
<FrameLayout {NS}
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:animateLayoutChanges="true">
{bg_view}    <FrameLayout android:id="@+id/content" android:layout_width="match_parent" android:layout_height="match_parent"
        android:padding="{'5dp' if bg else '2dp'}">
{inner}
        <ImageView android:id="@+id/update" style="@style/UpdateSymbol" android:layout_gravity="top|end" />
    </FrameLayout>
</FrameLayout>
'''


def hub(w="wrap_content", h="match_parent", extra=""):
    return f'''<ImageView android:id="@+id/hub" style="@style/Hub"
    android:layout_width="{w}" android:layout_height="{h}"{extra} />'''


def cell(i, labels, weight_dir="h"):
    w, h = ("0dp", "match_parent") if weight_dir == "h" else ("match_parent", "0dp")
    label = f'''
    <TextView android:id="@+id/c{i}t" style="@style/CellLabel" />''' if labels else ""
    return f'''<LinearLayout android:id="@+id/c{i}" style="@style/Cell"
    android:layout_width="{w}" android:layout_height="{h}" android:layout_weight="1">
    <ImageView android:id="@+id/c{i}i" style="@style/CellIcon" />{label}
</LinearLayout>'''


def indent(s, n):
    pad = " " * n
    return "\n".join(pad + line if line else line for line in s.split("\n"))


def row(n):
    cells = "\n".join(cell(i, False) for i in range(n))
    return f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="horizontal" android:gravity="center_vertical">
{indent(hub(extra=' android:layout_marginEnd="4dp"'), 8)}
{indent(cells, 8)}
    </LinearLayout>'''


def row_centred(left, right):
    """Hub in the middle: cells 0..left-1 before it, the rest after."""
    before = "\n".join(cell(i, False) for i in range(left))
    after = "\n".join(cell(i, False) for i in range(left, left + right))
    return f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="horizontal" android:gravity="center_vertical">
{indent(before, 8)}
{indent(hub(extra=' android:layout_marginStart="4dp" android:layout_marginEnd="4dp"'), 8)}
{indent(after, 8)}
    </LinearLayout>'''


def row_stacked():
    """2x1: two cells stacked on each side of the hub (cells 0,1 left; 2,3 right)."""
    def side(a, b):
        return f'''<LinearLayout android:layout_width="0dp" android:layout_height="match_parent"
    android:layout_weight="1" android:orientation="vertical">
{indent(cell(a, False, "v"), 4)}
{indent(cell(b, False, "v"), 4)}
</LinearLayout>'''
    return f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="horizontal" android:gravity="center_vertical">
{indent(side(0, 1), 8)}
{indent(hub(extra=' android:layout_marginStart="4dp" android:layout_marginEnd="4dp"'), 8)}
{indent(side(2, 3), 8)}
    </LinearLayout>'''


def column(n):
    cells = "\n".join(cell(i, False, "v") for i in range(n))
    return f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="vertical" android:gravity="center_horizontal">
{indent(hub("match_parent", "wrap_content", ' android:layout_marginBottom="4dp"'), 8)}
{indent(cells, 8)}
    </LinearLayout>'''


def ring(labels, w="match_parent", h="match_parent", weight=""):
    rows = []
    for r in RING_GRID:
        items = []
        for s in r:
            if s is None:
                items.append(hub("0dp", "match_parent", ' android:layout_weight="1" android:layout_margin="4dp"'))
            else:
                items.append(cell(s, labels))
        rows.append(f'''<LinearLayout android:layout_width="match_parent" android:layout_height="0dp"
    android:layout_weight="1" android:orientation="horizontal">
{indent(chr(10).join(items), 4)}
</LinearLayout>''')
    return f'''<LinearLayout android:layout_width="{w}" android:layout_height="{h}"{weight}
    android:orientation="vertical">
{indent(chr(10).join(rows), 4)}
</LinearLayout>'''


def recents(n, w="match_parent", h="wrap_content", weight=""):
    items = []
    for i in range(n):
        items.append(f'''<LinearLayout android:id="@+id/r{i}" style="@style/RecentRow">
    <ImageView android:id="@+id/r{i}i" style="@style/RecentIcon" />
    <LinearLayout android:layout_width="0dp" android:layout_height="wrap_content"
        android:layout_weight="1" android:orientation="vertical">
        <TextView android:id="@+id/r{i}t" style="@style/RecentTitle" />
        <TextView android:id="@+id/r{i}s" style="@style/RecentSub" />
    </LinearLayout>
    <ImageView android:id="@+id/r{i}p" style="@style/RemapPip" />
</LinearLayout>''')
    return f'''<LinearLayout android:layout_width="{w}" android:layout_height="{h}"{weight}
    android:orientation="vertical" android:paddingStart="4dp" android:paddingEnd="4dp">
    <TextView style="@style/SectionLabel" android:text="RECENT" />
{indent(chr(10).join(items), 4)}
</LinearLayout>'''


def wide():
    rows = []
    for r in range(2):
        cells = "\n".join(cell(r * 4 + i, True) for i in range(4))
        rows.append(f'''<LinearLayout android:layout_width="match_parent" android:layout_height="0dp"
    android:layout_weight="1" android:orientation="horizontal">
{indent(cells, 4)}
</LinearLayout>''')
    return f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="horizontal" android:gravity="center_vertical">
{indent(hub(extra=' android:layout_marginEnd="6dp" android:padding="6dp"'), 8)}
        <LinearLayout android:layout_width="0dp" android:layout_height="match_parent"
            android:layout_weight="1" android:orientation="vertical">
{indent(chr(10).join(rows), 12)}
        </LinearLayout>
    </LinearLayout>'''


LAYOUTS = {
    "widget_tile": f'    {hub("match_parent", "match_parent")}',
    "widget_row_s": row_stacked(),
    "widget_row": row(5),
    "widget_row_l": row(8),
    "widget_column": column(3),
    "widget_column_l": column(5),
    "widget_ring": indent(ring(False), 4),
    "widget_ring_l": indent(ring(True), 4),
    "widget_wide": wide(),
    "widget_tall": f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="vertical">
{indent(ring(False, h="0dp", weight=' android:layout_weight="1"'), 8)}
{indent(recents(3), 8)}
    </LinearLayout>''',
    "widget_xl": f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="vertical">
{indent(ring(True, h="0dp", weight=' android:layout_weight="1"'), 8)}
{indent(recents(3), 8)}
    </LinearLayout>''',
    "widget_xl_wide": f'''    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
        android:orientation="horizontal">
{indent(ring(True, w="0dp", weight=' android:layout_weight="1.3"'), 8)}
{indent(recents(4, w="0dp", h="match_parent", weight=' android:layout_weight="1"'), 8)}
    </LinearLayout>''',
}

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, inner in LAYOUTS.items():
        with open(os.path.join(OUT, name + ".xml"), "w") as f:
            # 1×1 is just the round icon, no background panel.
            f.write(root(inner, bg=name != "widget_tile"))
    print(f"wrote {len(LAYOUTS)} layouts")
